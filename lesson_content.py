def select_theme(title):
    t = title.lower()
    # priority matches
    priorities = [
        "english in action","nationalities","everyday things","good and bad habits","jobs around the house",
        "good day","how was","bad day","family photos","study","party","plans","journey","weather",
        "shopping","travel","education","internet","news","health","money","future","culture",
        "hello","jobs","famil","numbers","town","wifi","expensive","friend","got it","don't",
        "week","food","habits","house","skills","questions","young","places","photos","hobbies","goals","work"
    ]
    for key in priorities:
        if key in t and key in THEMES:
            return key
    # word fallback
    for key in THEMES:
        if any(tok and tok in t for tok in key.split()):
            return key
    return "english in action"

def vocabulary_for(title, level):
    return THEMES.get(select_theme(title), THEMES["english in action"])


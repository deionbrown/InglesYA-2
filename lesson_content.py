def evaluation_for(title, level, goal, grammar):
    vocab = vocabulary_for(title, level)
    reading = reading_for(title, level, goal)
    ex = examples_for(title, level, goal)

    v1_en,v1_es = vocab[0]
    v2_en,v2_es = vocab[1] if len(vocab)>1 else vocab[0]
    v3_en,v3_es = vocab[2] if len(vocab)>2 else vocab[0]

    return [
        (f"¿Cómo se dice «{v1_es}» en inglés?", v1_en),
        (f"¿Qué significa «{v2_en}» en español?", v2_es),
        (f"Escribe en inglés la palabra o expresión que significa «{v3_es}».", v3_en),
        (f"Traduce al español: {ex[0][0]}", ex[0][1]),
        (f"Traduce al inglés: {ex[1][1]}", ex[1][0]),
        (f"¿Cuál es el enfoque gramatical de esta lección?", grammar),
        (f"Escribe una oración propia usando el enfoque «{grammar}».",
         f"Respuesta abierta. Ejemplo: {ex[0][0]}"),
        ("Según la lectura, ¿cuál es la idea principal?",
         reading[0][1] + " " + reading[-1][1]),
        (f"Escribe una frase en inglés relacionada con «{title}».",
         f"Respuesta abierta. Ejemplo: {ex[2][0]}"),
        ("¿Cuál es el objetivo comunicativo de la lección?", goal),
    ]

def lesson_pack(title, level, goal, grammar=None):
    return {
        "vocabulary": vocabulary_for(title, level),
        "examples": examples_for(title, level, goal),
        "reading": reading_for(title, level, goal),
        "dialogue": dialogue_for(title, level, goal),
        "evaluation": evaluation_for(title, level, goal, grammar or ""),
    }



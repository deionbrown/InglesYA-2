_original_vocabulary_for = vocabulary_for

def vocabulary_for(title, level):
    """Return a substantial lesson vocabulary set, with no duplicates."""
    base = list(_original_vocabulary_for(title, level))
    key = select_theme(title)
    base.extend(VOCAB_EXTENSIONS.get(key, []))

    # Higher-level/core language: useful when a topic has a short theme list.
    if level in LEVEL_CORE:
        base.extend(LEVEL_CORE[level])

    # Deduplicate while preserving order.
    seen=set()
    result=[]
    for en,es in base:
        norm=en.strip().lower()
        if not norm or norm in seen:
            continue
        seen.add(norm)
        result.append((en,es))

    # Guarantee a useful minimum without inventing a claim that these are exact Pearson wordlists.
    if len(result) < 15:
        fallback = [
            ("example","ejemplo"),("meaning","significado"),("sentence","oración"),
            ("question","pregunta"),("answer","respuesta"),("practice","práctica"),
            ("understand","entender"),("remember","recordar"),("use","usar"),
        ]
        for item in fallback:
            if item[0].lower() not in seen:
                result.append(item); seen.add(item[0].lower())
            if len(result) >= 15:
                break
    return result

